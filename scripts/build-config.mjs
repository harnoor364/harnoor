/* =====================================================================
   Netlify build step: writes js/supabase-config.js from environment
   variables, so no key is hard-coded in the repository.

   Set these in Netlify → Site configuration → Environment variables:
     SUPABASE_URL       e.g. https://abcdefghijklm.supabase.co
     SUPABASE_ANON_KEY  the PUBLIC "anon" / "publishable" key

   The public key is safe in a browser ONLY because Row Level Security
   is on (see docs/supabase/setup.sql). The build FAILS if it is given a
   secret / service-role key by mistake, so that key can never be published.
   ===================================================================== */
import fs from "node:fs";

// Default: the live Upward Web project. Both values are PUBLIC (they ship to
// every browser); Row Level Security keeps clients' data private. Netlify
// environment variables, when set, override these.
const DEFAULT_URL = "https://elyfxcnwiokdbsjnrszy.supabase.co";
const DEFAULT_KEY = "sb_publishable_Ajq8vtc-bWSKaYAtfnpnQg_h4fJ_o7U";

const url = (process.env.SUPABASE_URL || DEFAULT_URL).trim().replace(/\/+$/, "");
const key = (process.env.SUPABASE_ANON_KEY || DEFAULT_KEY).trim();
const OUT = "js/supabase-config.js";

function fail(msg) {
  console.error(`build-config: ${msg}`);
  process.exit(1);
}

function roleOf(jwt) {
  try {
    const payload = JSON.parse(Buffer.from(jwt.split(".")[1].replace(/-/g, "+").replace(/_/g, "/"), "base64").toString("utf8"));
    return payload.role || "";
  } catch {
    return "";
  }
}

if (!url && !key) {
  console.log("build-config: SUPABASE_URL / SUPABASE_ANON_KEY not set; client portal stays switched off.");
} else {
  if (!/^https:\/\/[a-z0-9-]+\.supabase\.co$/.test(url)) fail("SUPABASE_URL must look like https://<project-ref>.supabase.co");
  if (/^sb_secret_/.test(key)) fail("SUPABASE_ANON_KEY is a SECRET key. Use the public anon/publishable key instead, and rotate the secret key.");
  if (key.split(".").length === 3 && roleOf(key) !== "anon") fail(`SUPABASE_ANON_KEY has role "${roleOf(key) || "unknown"}", expected "anon". Never put the service_role key in the website.`);
  if (!(key.split(".").length === 3 || /^sb_publishable_/.test(key))) fail("SUPABASE_ANON_KEY doesn't look like a Supabase anon or publishable key.");
}

const body = `/* Generated by scripts/build-config.mjs during the Netlify build. Do not edit by hand. */
window.SUPABASE_CONFIG = ${JSON.stringify({ url, anonKey: key })};
`;
fs.writeFileSync(OUT, body);
console.log(`build-config: wrote ${OUT}${url ? ` for ${url}` : " (portal off)"}`);
